const assert = require('node:assert/strict');
const { pathToFileURL } = require('node:url');
const E = require('../dist/engine.js');
(async () => {
  const M = await import(pathToFileURL(require('node:path').resolve('dist/eva-model.js')));
  let s = {...E.initial(), expedition:M.newExpedition()};
  const act = id => { const r=M.evaAction(s,id); assert.equal(r.ok,true,r.message); s=r.state; };
  const untouched=JSON.stringify(s);
  assert.equal(M.evaAction(s,'exit').ok,false);
  assert.equal(JSON.stringify(s),untouched);
  act('suit'); act('fill');
  assert.equal(s.expedition.suit+s.expedition.oxygen,60,'fill transfers, never creates air');
  act('exit');
  const standing=M.evaTick(s,1), running=M.evaTick(s,1,true);
  assert.ok(Math.abs(standing.expedition.suit-39.7)<1e-8);
  assert.ok(Math.abs(running.expedition.suit-39.4)<1e-8);
  act('ice'); act('rock'); act('enter');
  assert.equal(M.evaTick(s,1),s,'cabin does not drain suit');
  act('oxygen'); assert.equal(s.expedition.complete,false,'must actually melt the recovered ice');
  act('melt'); act('oxygen'); assert.equal(s.expedition.complete,true);
  assert.equal(M.evaAction(s,'exit').ok,false,'one outing per shift after tutorial');
  const science=s.science, power=s.power;
  act('scan'); assert.equal(s.science,science+10); assert.equal(s.power,power-5);
  assert.equal(M.evaAction(s,'scan').ok,false,'no repeated reward without a rock');
  const water=s.expedition.water; act('plants'); assert.equal(s.expedition.water,water-10);
  const initialOxygen=s.expedition.oxygen;
  for(let d=0;d<7;d++) {
    const copy=JSON.stringify(s), preview=E.forecast(s,0), next=E.decide(s,0);
    assert.equal(JSON.stringify(s),copy,'forecast and decide must not mutate inventory');
    assert.deepEqual(preview.deltas,next.log.at(-1).deltas);
    assert.equal(next.expedition.oxygen,initialOxygen-(d+1)*4);
    s=next;
  }
  assert.equal(s.day,7);
  let shortage={...E.initial(),expedition:{...M.newExpedition(),oxygen:0,food:0}};
  const preview=E.forecast(shortage,0), next=E.decide(shortage,0);
  assert.deepEqual(preview.deltas,next.log.at(-1).deltas);
  assert.ok(preview.notes.some(n=>n.text.includes('lost 5')));
  let rescue={...E.initial(),expedition:{...M.newExpedition(),outside:true,suited:true,suit:0.1}};
  const rescued=M.evaTick(rescue,1); assert.equal(rescued.expedition.outside,false); assert.equal(rescued.safety,55);
  let storm={...E.initial(),day:3,expedition:{...M.newExpedition(),suited:true,suit:40}};
  assert.equal(M.evaAction(storm,'exit').ok,false);
  global.days=E.days;
  const storage=new Map(); global.localStorage={getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,v),removeItem:k=>storage.delete(k)};
  const S=await import(pathToFileURL(require('node:path').resolve('dist/mission-session.js')));
  S.saveMission(E.initial()); const legacy=storage.get('lunar-frontier-mission-v2');
  assert.equal(S.saveMission(s),true);
  assert.deepEqual(S.loadMission(E.initial,E.decide,{expedition:true}),s);
  assert.equal(storage.get('lunar-frontier-mission-v2'),legacy,'rollback save remains intact');
  assert.equal(S.loadMission(E.initial,E.decide).expedition,undefined,'2D keeps its separate legacy mission');
  const corrupt=structuredClone(s); corrupt.expedition.suit=-1;
  assert.equal(S.validExpeditionSave({version:1,state:corrupt}),false);
  console.log('EVA costs, conservation, collection, rescue, seven shifts, forecast parity and save/rollback tests passed.');
})().catch(e=>{console.error(e);process.exitCode=1;});
